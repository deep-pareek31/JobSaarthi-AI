    fun toJobDto(detail: JobDetailDto): JobDto {
        return JobDto(
            id = detail.id,
            title = detail.title,
            employmentType = detail.employmentType,
            department = detail.department,
            location = detail.location,
            country = detail.country,
            city = detail.city,
            remoteType = detail.remoteType,
            experienceMin = detail.experienceMin,
            experienceMax = detail.experienceMax,
            salaryMin = detail.salaryMin,
            salaryMax = detail.salaryMax,
            salaryCurrency = detail.salaryCurrency,
            stipend = detail.stipend,
            postedAt = detail.postedAt,
            lastVerifiedAt = detail.lastVerifiedAt,
            applicationDeadline = detail.applicationDeadline,
            deadlineSource = detail.deadlineSource,
            applicationUrl = detail.applicationUrl,
            sourceUrl = detail.sourceUrl,
            status = detail.status,
            company = detail.company,
            source = detail.source,
            matchPercentage = detail.matchPercentage,
            whyMatches = detail.whyMatches,
            missingSkills = detail.missingSkills
        )
    }

    fun toEntity(detail: JobDetailDto, isToday: Boolean, isRecommended: Boolean): JobEntity {
        return JobEntity(
            id = detail.id,
            title = detail.title,
            companyName = detail.company.name,
            companyLogoUrl = detail.company.logoUrl,
            employmentType = detail.employmentType,
            location = detail.location,
            remoteType = detail.remoteType,
            experienceMin = detail.experienceMin,
            experienceMax = detail.experienceMax,
            salaryMin = detail.salaryMin,
            salaryMax = detail.salaryMax,
            stipend = detail.stipend,
            postedAt = detail.postedAt,
            applicationDeadline = detail.applicationDeadline,
            deadlineSource = detail.deadlineSource,
            applicationUrl = detail.applicationUrl,
            sourceName = detail.source.name,
            matchPercentage = detail.matchPercentage,
            isToday = isToday,
            isRecommended = isRecommended
        )
    }

